# peticion de notas 

print("¡Bienvenido al sistema de promedios o ver tu NEM!")
while True:
    try:
        cantidad_notas = int(input("¿Cuántas notas deseas ingresar? "))
        
    except ValueError:
       print("Debes ingresar un numero, no una letra.")
       continue
       
    if cantidad_notas < 3 or cantidad_notas > 8:
        print("Cantidad no válida, debe ser de 3 a 8.")
    else:
        break
# calculo de promedio    
notas = []

for i in range(cantidad_notas):
    
    while True:
        
      try:
         nota = float(input(f"Ingresa la nota {i + 1} (20-70): "))
         
         if nota < 20 or nota > 70 :
             print("Nota inválida. Por favor, ingresa una nota entre 20 y 70")
         else:
             notas.append(nota)
             break
         
      except ValueError: 
          print("Debes ingresar un número, no una letra.")
  
else:
    promedio = sum(notas) / len(notas)
    
    promediofinal = round(promedio / 10, 2) 
  
    # calcular el nem del usuario
    
    print(f"Tu promedio es: {promediofinal:.2f}")
    
    print("deseas calcular el NEM de tu promedio?")
    
    while True:
        respuesta = input("Ingresa 'sí' o 'no': ").strip().lower()
        if respuesta in ("si", "sí", "no"):
            break
        print("use si o no para continuar, vuelva a intentar")
 
    if respuesta == 'no':
        print("¡Gracias por usar el sistema de notas!")
        exit()
        
    elif respuesta == 'si' or respuesta == 'sí':
        
        print("en que colegio estudiaste?")
        
        print("1. Científico Humanista")
        
        print("2. Técnico Profesional")

        while True:
            tipo_colegio = input("Ingresa el número correspondiente a tu tipo de colegio: ").strip()
           
            if tipo_colegio == '1':
              
                tabla_elegida = tabla_cientifica
                break
            elif tipo_colegio == '2':
              
                tabla_elegida = tabla_tecnica
                break
            else:
                print("opcion no valida")
       
        clave_promedio = round(promediofinal * 100)
        
        nem = tabla_elegida.get(clave_promedio)
        
        if nem is not None: 
            print(f"tu puntaje NEM es {nem}")
        else:
            print("no se pudo encontrar tu promedio en la tabla")
